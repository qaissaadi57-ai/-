export function getCitiesByGovernorate(govValue: string): string[] {
  if (!govValue) return [];
  const found = IRAQ_GOVERNORATES.find(
    (g) => g.value === govValue || g.name.includes(govValue) || govValue.includes(g.value)
  );
  return found ? found.cities : [];
}
